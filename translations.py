def t(key, lang=DEFAULT_LANGUAGE):
    """Look up a UI string. Falls back to English, then to the raw key,
    so a missing translation never crashes a page - it's just visibly
    untranslated, which is easy to spot and fix."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANGUAGE])
    return lang_dict.get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)


